#!/usr/bin/env python3
"""Quick standards-library-only validation of the docs and mod candidate list."""
import csv
import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = [
    "README.md", "LICENSE", "THIRD_PARTY_NOTICES.md", "AGENTS.md",
    "docs/README.md", "docs/design/vision.md", "docs/design/professions.md",
    "docs/design/general-skills.md", "docs/technical/mod-audit.md",
    "docs/technical/mod-candidates.csv", "docs/production/mvp-v0.1.md",
    "docs/legal/third-party-policy.md", "docs/legal/asset-register.csv",
]
issues = []
for name in REQUIRED:
    if not (ROOT / name).is_file():
        issues.append("Required file missing: " + name)

link_pattern = re.compile(r"(?<!!)\[[^\]]+\]\(([^)]+)\)")
IGNORED_FOLDERS = {"build", ".gradle", "node_modules", ".git"}   # generated or disposable copies (journey and probe runs copy the module with its README)
for document in ROOT.rglob("*.md"):
    relative_parts = document.relative_to(ROOT).parts
    if IGNORED_FOLDERS & set(relative_parts) or any(part.startswith("run-") for part in relative_parts):
        continue
    for raw in link_pattern.findall(document.read_text(encoding="utf-8")):
        target = raw.split()[0].strip("<>")
        if target.startswith(("#", "mailto:")):
            continue
        parsed = urlsplit(target)
        if parsed.scheme or target.startswith("//") or not parsed.path:
            continue
        dest = (document.parent / unquote(parsed.path)).resolve()
        if not dest.is_relative_to(ROOT.resolve()) or not dest.exists():
            issues.append("Broken link: " + str(document.relative_to(ROOT)) + " -> " + target)

csv_path = ROOT / "docs/technical/mod-candidates.csv"
if csv_path.exists():
    with csv_path.open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    ids = set()
    for row in rows:
        candidate_id = (row.get("id") or "").strip()
        if not candidate_id or candidate_id in ids:
            issues.append("Blank or duplicate mod candidate ID: " + candidate_id)
        ids.add(candidate_id)
        if not (row.get("project_url") or "").startswith("https://"):
            issues.append("Invalid source URL for " + candidate_id)
        if (row.get("status") or "") not in ("candidate", "testing", "approved_for_local_use", "retired"):
            issues.append("Invalid status for " + candidate_id)


# Also protect against accidental commits of third-party binaries or private worlds.
try:
    import subprocess
    tracked = subprocess.check_output(["git", "ls-files"], cwd=ROOT, text=True).splitlines()
    blocked_suffixes = {".jar", ".zip", ".7z", ".rar", ".mca", ".mcr", ".schem", ".schematic", ".nbt", ".litematic", ".key", ".pem"}
    blocked_directories = {"world", "worlds", "saves", "playerdata", "secrets", "backups"}
    permitted_template = "rpg-core/src/main/resources/data/underground_city/structures/empty.nbt"
    permitted_sha256 = "c2e9e1dbc61b46857273e9ac52f7b9b9bdf503779068e1609a84e29fd5265cf0"
    # The standard Gradle bootstrap (Apache-2.0, generated by Gradle 8.14.3); CI also runs gradle/actions/wrapper-validation
    # against Gradle's published checksums. Replacing it requires updating this hash on purpose.
    permitted_wrapper = "gradle/wrapper/gradle-wrapper.jar"
    permitted_wrapper_sha256 = "7d3a4ac4de1c32b59bc6a4eb8ecb8e612ccd0cf1ae1e99f66902da64df296172"
    import hashlib
    for tracked_file in tracked:
        location = Path(tracked_file)
        if tracked_file == permitted_wrapper:
            digest = hashlib.sha256((ROOT / tracked_file).read_bytes()).hexdigest()
            if digest != permitted_wrapper_sha256:
                issues.append("Gradle wrapper jar changed without updating the pinned hash: " + tracked_file)
            continue
        if tracked_file == permitted_template:
            digest = hashlib.sha256((ROOT / tracked_file).read_bytes()).hexdigest()
            if digest != permitted_sha256:
                issues.append("Allowed GameTest template changed without explicit rights review: " + tracked_file)
            continue
        if location.suffix.lower() in blocked_suffixes:
            issues.append("Restricted binary or secret-like file tracked: " + tracked_file)
        if any(part.lower() in blocked_directories for part in location.parts[:-1]):
            issues.append("Restricted world/save directory tracked: " + tracked_file)
except (OSError, subprocess.CalledProcessError):
    issues.append("Cannot check tracked files: git is required to validate repository contents")

if issues:
    print("Repository validation failed:")
    for item in issues:
        print(" -", item)
    sys.exit(1)
print("Repository validation passed: required files, local links, and candidate IDs.")
