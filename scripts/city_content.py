#!/usr/bin/env python3
"""The furnished cities: original Lost Cities buildings for the three islands, written as code (D-117), packaged as the low-code mod ``underground_city_furnished``.

Why a separate mod and not more files in the archipelago package: the buildings are furnished with Modern Life's blocks (already in the development pack as a runtime-only
download), and a Lost Cities palette that names a block that is not installed is a world-generation error. The mod depends on Modern Life, on the archipelago package and
on Core, so it only exists in a game that has all three. It is opt-in (``-PucExtraSets=furnished``) and a world remembers that it was made with it
(``GenerationPackGuard``): the next chunks of an existing world are never generated by new rules.

    python scripts/emit_dev_world_pack.py --layout furnished        write content/generated/world-furnished
    python scripts/emit_dev_world_pack.py --layout furnished --check    fail when it is out of date
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import citykit  # noqa: E402

MOD_ID = "underground_city_furnished"
NAMESPACE = "underground_city"


def json_bytes(document) -> bytes:
    return (json.dumps(document, indent=2, sort_keys=True) + "\n").encode("utf-8")


def all_buildings() -> list[citykit.Building]:
    import city_valewood, city_ironhaven, city_blackwater   # noqa: E401
    return city_valewood.buildings() + city_ironhaven.buildings() + city_blackwater.buildings()


def citystyles(buildings: list[citykit.Building]) -> dict[str, dict]:
    """One city style per city: it inherits Lost Cities' standard style (streets, parks, fountains, bridges) and replaces the buildings it chooses from."""
    import city_valewood, city_ironhaven, city_blackwater   # noqa: E401
    out = {}
    for module in (city_valewood, city_ironhaven, city_blackwater):
        style = module.citystyle(buildings)
        if style is not None:
            out[module.CITY] = style
    return out


# classes the furnished buildings need beyond the stock ones (cottage, flat_block, flat_tower, workshop, office, vault, public)
# Each class has a tier (D-144): 1 shabby, 2 modest, 3 comfortable, 4 well-off, 5 wealthy, 6 exceptional, a category and (D-157) a grade range its buildings move in by neighbourhood
# (Core's classes.json holds the security of each graded tier; the cameras and panels a plan carries follow the class's own tier). "panel": False keeps a class's alarm without an alarm panel in its plan, so moving a
# building to such a class changes what Core does with it and never how its chunks generate.
NEW_SECURITY_CLASSES = {
    "storefront": {"label": "shop", "category": "commercial", "grade": [1, 4], "tier": 3, "lock_profile": "commercial", "locked_exterior": True, "stash_policy": "underground_city:office", "stash_chance": 0.5,
                   "response": {"alarm_chance": 0.5, "dispatch_seconds": 90, "officers": 1, "window_seconds": 120}},
    "warehouse": {"label": "warehouse", "category": "industrial", "grade": [3, 5], "tier": 4, "lock_profile": "secured", "locked_exterior": True, "stash_policy": "underground_city:industrial", "stash_chance": 0.7,
                  "response": {"alarm_chance": 0.6, "dispatch_seconds": 100, "officers": 1, "window_seconds": 120}},
    "club": {"label": "club", "category": "commercial", "tier": 5, "lock_profile": "high_security", "locked_exterior": True, "stash_policy": "underground_city:illegal_cache", "stash_chance": 0.6,
             "response": {"alarm_chance": 0.8, "dispatch_seconds": 60, "officers": 2, "window_seconds": 150}},
    # a white-brick townhouse is the better-off house of Valewood's middle: tier 4 with a camera and a panel, so the city has wealthy targets too (D-157: the survey of a new world found none)
    "townhouse": {"label": "townhouse", "category": "residential", "grade": [3, 5], "tier": 4, "lock_profile": "secured", "locked_exterior": True, "stash_policy": "underground_city:apartment_affluent",
                  "stash_chance": 0.7, "response": {"alarm_chance": 0.55, "dispatch_seconds": 100, "officers": 1, "window_seconds": 120}},
    "house": {"label": "house", "category": "residential", "grade": [2, 5], "tier": 3, "lock_profile": "deadbolt", "locked_exterior": True, "stash_policy": "underground_city:apartment_affluent", "stash_chance": 0.6, "panel": False,
              "response": {"alarm_chance": 0.4, "dispatch_seconds": 110, "officers": 1, "window_seconds": 120}},
}
STOCK_SECURITY_CLASSES = {"cottage", "flat_block", "flat_tower", "workshop", "office", "vault", "public"}


# stock classes that have an alarm (a "response" in data/underground_city/building_security/classes.json)
ALARMED_STOCK_CLASSES = {"flat_block", "flat_tower", "workshop", "office", "vault"}
NOT_A_WALL = ("door", "glass", "pane", "bars", "trapdoor", "fence", "air", "sign", "banner", "ladder", "torch", "lantern", "button", "lever", "slab", "stairs", "carpet", "bed",
              "cake", "pot", "chest", "barrel", "campfire", "rod", "chain", "wall_", "candle", "rail", "plate", "flower", "sapling", "hopper", "table", "bookshelf")


def alarmed(security: str) -> bool:
    spec = NEW_SECURITY_CLASSES.get(security, {})
    return security in ALARMED_STOCK_CLASSES or ("response" in spec and spec.get("panel", True))


# Cameras by tier (D-149): a well-off building watches its entry, a wealthy or exceptional one its two first street doors; nothing below. A camera is a Modern Life CCTV camera, which Core
# watches with (SecurityDevices: a 12-block cone with a line of sight); shops keep the cameras their plans already have.
CAMERAS_BY_TIER = {4: 1, 5: 2, 6: 2}
STOCK_TIERS = {"cottage": 1, "flat_block": 2, "flat_tower": 4, "workshop": 3, "office": 4, "vault": 6, "public": 0}


def tier_of(security: str) -> int:
    return NEW_SECURITY_CLASSES[security]["tier"] if security in NEW_SECURITY_CLASSES else STOCK_TIERS.get(security, 0)


# Where a camera may hang. Lost Cities writes a part's blocks lower x and lower z first, and as each block goes in it asks the blocks beside it to update their shape; a wall-hung block
# then checks its wall in the world, where a block written after it is not there yet, and turns to air. So a camera whose wall comes later never exists: the first cameras by tier hung
# over the club's and the warehouse's south doors, looking north at a wall written after them, and the generated worlds had none (found by the advanced burglary scenario through a
# real client and read back from its world). A camera therefore hangs on a wall to its west (looking east) or to its north (looking south), or on nothing (as the offices' do).
CAMERA_WALL_FIRST = ("east", "south")
CAMERA_REACH = 10          # the door's inside within this many blocks (Core's cone is 12 blocks long)
CAMERA_HALF_ANGLE = 40     # and this far either side of where the camera looks (Core's cone is 50 degrees either side)


def wall_at(part: citykit.Part, x: int, y: int, z: int) -> bool:
    """A plain block of the part a wall-hung thing can be fixed to: no furniture, shelf, glass, door or anything that is not a whole block."""
    c = part.get(x, y, z)
    if c == " ":
        return False
    spec = part.palette.entries[c]
    if not isinstance(spec, str) or not spec.startswith("minecraft:") or any(word in spec for word in NOT_A_WALL):
        return False                                                           # furniture, a shelf, a cake on a counter, a monitor: not a wall
    return "[" not in spec or spec.split("[", 1)[1].rstrip("]").split("=")[0] == "axis"


def camera_survives(part: citykit.Part, x: int, y: int, z: int, facing: str) -> bool:
    """Whether a wall-hung camera at this cell, looking this way, outlives Lost Cities' writing of the part: nothing behind it, or a wall that is written before it."""
    back = citykit.DIRS[facing]
    return part.get(x - back[0], y, z - back[1]) == " " or facing in CAMERA_WALL_FIRST


def camera_spot(part: citykit.Part, door: tuple[int, int], out: tuple[int, int]) -> tuple[int, int, int, str] | None:
    """The best cell high in the room from which a camera sees a person coming in by a street door: the cell and the one below it empty, one of the first four cells inside the
    door (the way a person walks in) within reach, well inside the cone, and nothing in the part between the lens and a person's head there. It must outlive Lost Cities' writing (``camera_survives``); a camera
    on a wall is preferred to one hung under the ceiling with nothing behind it (as the offices' are), and a nearer one to a farther."""
    insides = [(door[0] - out[0] * k, door[1] - out[1] * k) for k in (1, 2, 3, 4)]
    best = None
    for facing, (fx, fz) in citykit.DIRS.items():
        for y in (4, 3):
            for x in range(1, citykit.SIZE - 1):
                for z in range(1, citykit.SIZE - 1):
                    if part.get(x, y, z) != " " or part.get(x, y - 1, z) != " " or not camera_survives(part, x, y, z, facing):
                        continue
                    on_wall = wall_at(part, x - fx, y, z - fz)
                    if not on_wall and (part.get(x - fx, y, z - fz) != " " or not wall_at(part, x, y + 1, z)):
                        continue                                                   # neither on a wall nor hung under the ceiling
                    for inside in insides:
                        vx, vz = inside[0] - x, inside[1] - z
                        d = math.hypot(vx, vz)
                        if d < 1.5 or d > CAMERA_REACH or (vx * fx + vz * fz) / d < math.cos(math.radians(CAMERA_HALF_ANGLE)):
                            continue
                        steps = int(d * 3) + 1
                        if any(part.get(round(x + vx * k / steps), round(y + (1.6 - y) * k / steps), round(z + vz * k / steps)) != " " for k in range(1, steps)):
                            continue
                        key = (0 if on_wall else 1, round(d), y != 4, facing, x, z)
                        if best is None or key < best[0]:
                            best = (key, (x, y, z, facing))
    return best[1] if best else None


# What else Lost Cities' writing order takes (read back from generated worlds, plan against world): a carpet or a garden plant on a floor of its own part (the floor is written after it),
# and a shelf or a screen on a wall written after it. Small flowers are not lost: Lost Cities places them itself, after the part. After everything is placed, each such block becomes one
# that needs no support: a carpet becomes its colour of wool in the floor under it, a berry bush a flowering azalea, a fern or grass a cornflower, a wall shelf a bookshelf (still searched
# as one), a screen a monitor, and any other wall-hung piece is left out.
FLOOR_PLANTS = {"minecraft:sweet_berry_bush": "minecraft:flowering_azalea_leaves[persistent=true]", "minecraft:fern": "minecraft:cornflower", "minecraft:grass": "minecraft:cornflower",
                "minecraft:tall_grass": "minecraft:cornflower", "minecraft:large_fern": "minecraft:cornflower", "minecraft:dead_bush": None}
WALL_HUNG = ("wall_shelf", "cctv_screen", "cctv_camera", "mirror", "light_switch", "wall_socket", "electrical_outlet", "canvas")


def wall_hung_survives(part: citykit.Part, x: int, y: int, z: int, spec: str) -> bool:
    """A wall-hung block (its wall behind it, opposite the way it faces) outlives Lost Cities' writing when that wall is written first, or when there is nothing behind it."""
    facing = spec.split("facing=", 1)[1].split(",", 1)[0].rstrip("]") if "facing=" in spec else ""
    if facing not in citykit.DIRS:
        return True
    return camera_survives(part, x, y, z, facing)


def fit_for_lost_cities(b: citykit.Building) -> list[str]:
    """Makes every block of the building that Lost Cities would turn to air into one it keeps (see ``FLOOR_PLANTS``); returns what was changed, for the tests."""
    changed = []
    for part, _ in b.parts:
        for y in range(citykit.FLOOR_H):
            for z in range(part.zsize):
                for x in range(part.xsize):
                    c = part.get(x, y, z)
                    if c == " ":
                        continue
                    spec = part.palette.entries[c]
                    if not isinstance(spec, str):
                        continue
                    name = spec.split("[", 1)[0]
                    on_own_floor = y >= 1 and part.get(x, y - 1, z) != " "
                    if name.startswith("minecraft:") and name.endswith("_carpet") and on_own_floor:
                        if wall_at(part, x, y - 1, z):
                            part.put(x, y - 1, z, name.replace("_carpet", "_wool"))
                        part.put(x, y, z, None)
                        changed.append(f"{part.name} {x},{y},{z} {name} -> wool floor")
                    elif name in FLOOR_PLANTS and on_own_floor:
                        part.put(x, y, z, FLOOR_PLANTS[name])
                        changed.append(f"{part.name} {x},{y},{z} {name} -> {FLOOR_PLANTS[name]}")
                    elif any(word in name for word in WALL_HUNG) and not wall_hung_survives(part, x, y, z, spec):
                        facing = spec.split("facing=", 1)[1].split(",", 1)[0].rstrip("]")
                        replacement = "minecraft:bookshelf" if "wall_shelf" in name else citykit.ml("monitor", facing=facing) if "cctv_screen" in name else None
                        part.put(x, y, z, replacement)
                        changed.append(f"{part.name} {x},{y},{z} {spec} -> {replacement}")
    return changed


def place_cameras(b: citykit.Building) -> None:
    """The building's cameras by its tier (D-149): inside, high in the room near a street door and looking at the way in, so that whoever comes in by that door walks into its field;
    only where Lost Cities lets one stand (see ``CAMERA_WALL_FIRST``). A door with no such place in reach gets none; a building that already has a camera in its plan keeps it."""
    wanted = CAMERAS_BY_TIER.get(tier_of(b.security), 0)
    ground = [part for part, flags in b.parts if flags.get("ground")]
    if not wanted or not ground:
        return
    part = ground[0]
    if any(isinstance(spec, str) and "cctv_camera" in spec for spec in part.palette.entries.values()):
        return
    placed = 0
    for door in (s for s in b.spots if s.kind == "door"):
        if placed >= wanted:
            break
        spot = camera_spot(part, (door.x, door.z), citykit.DIRS[door.facing])
        if spot is None:
            continue
        x, y, z, facing = spot
        part.put(x, y, z, citykit.ml("cctv_camera", facing=facing))
        placed += 1


def place_alarm_panel(b: citykit.Building) -> None:
    """The building's alarm panel (D-128): on a plain inside wall a few steps in from the first street door (the door's own wall when it can), at head height (layer 2 of the ground floor), facing into the room,
    and an ``alarm`` spot that tells Core where it is. A building whose class has no alarm gets none."""
    if not alarmed(b.security) or any(s.kind == "alarm" for s in b.spots):
        return
    ground = [part for part, flags in b.parts if flags.get("ground")]
    if not ground:
        raise ValueError(f"{b.id}: no ground floor for the alarm panel")
    part = ground[0]

    def solid(x: int, y: int, z: int) -> bool:
        return wall_at(part, x, y, z)

    for door in (s for s in b.spots if s.kind == "door"):
        out = citykit.DIRS[door.facing]
        start = (door.x - out[0], door.z - out[1])
        if part.get(start[0], 2, start[1]) != " ":
            continue
        # the open cells at head height a few steps in from the door, nearest first; a panel goes on the first plain wall one of them has beside it (the door's own wall first)
        seen, frontier, best = {start}, [start], None
        for distance in range(1, 6):
            nxt = []
            for (x, z) in frontier:
                for d in citykit.DIRS.values():
                    c = (x + d[0], z + d[1])
                    if c in seen or not (1 <= c[0] < citykit.SIZE - 1 and 1 <= c[1] < citykit.SIZE - 1) or part.get(c[0], 2, c[1]) != " ":
                        continue
                    seen.add(c)
                    nxt.append(c)
            for (x, z) in sorted(nxt):
                for name in [door.facing] + [n for n in ("north", "east", "south", "west") if n != door.facing]:
                    d = citykit.DIRS[name]
                    if solid(x + d[0], 2, z + d[1]):
                        best = (x, z, citykit.OPPOSITE[name])
                        break
                if best:
                    break
            if best:
                break
            frontier = nxt
        if best:
            px, pz, facing = best
            part.put(px, 2, pz, f"underground_city:alarm_panel[facing={facing},light=off]")
            b.spots.append(citykit.Spot("alarm", px, 2, pz, facing, f"alarm panel by the {door.note or 'door'}"))
            return
    raise ValueError(f"{b.id}: no plain wall beside a street door for the alarm panel")


def package() -> dict[str, bytes]:
    import city_valewood, city_ironhaven, city_blackwater   # noqa: E401
    files: dict[str, bytes] = {}
    files["META-INF/mods.toml"] = (
        'modLoader="lowcodefml"\nloaderVersion="[47,)"\nlicense="All Rights Reserved"\n\n[[mods]]\n'
        f'modId="{MOD_ID}"\nversion="0.1.0"\n'
        'displayName="Underground City: Furnished Cities"\n'
        'description="Original furnished buildings for the three islands (Modern Life furniture)."\n'
        + "".join(f'\n[[dependencies.{MOD_ID}]]\nmodId="{dep}"\nmandatory=true\nversionRange="{rng}"\nordering="AFTER"\nside="BOTH"\n'
                 for dep, rng in (("lostcities", "[1.20-7.5.5]"), ("underground_city", "[0.1.0,)"), ("underground_city_archipelago", "[0.1.0,)"), ("modernlife", "[1.0,)")))
    ).encode()
    files["pack.mcmeta"] = json_bytes({"pack": {"pack_format": 15, "description": "Underground City furnished cities (original)"}})
    buildings = all_buildings()
    seen = set()
    for b in buildings:
        if b.id in seen:
            raise ValueError("duplicate building id " + b.id)
        seen.add(b.id)
        place_alarm_panel(b)
        place_cameras(b)
        fit_for_lost_cities(b)
        for path, doc in b.files(NAMESPACE).items():
            files[f"data/{NAMESPACE}/{path}"] = json_bytes(doc)
        files[f"data/{NAMESPACE}/city_buildings/{b.id}.json"] = json_bytes(b.core_data())
    for city, style in citystyles(buildings).items():
        files[f"data/{NAMESPACE}/lostcities/citystyles/{city}.json"] = json_bytes(style)
    # Lost Cities scatters 5 to 10 chains and 5 to 20 cobwebs through every building of a style that carries the "rubble" tag, which the standard style does and no child can remove; a lived-in
    # home has none. The two stuff objects are replaced by ones that place nothing (a count of zero: Lost Cities draws min + nextInt(max - min), so max must be above min; and only in the Nether), in this package only (it exists only in a world made with it, GenerationPackGuard).
    for name, column in (("chains", "{"), ("cobweb", "\\")):
        files[f"data/lostcities/lostcities/stuff/{name}.json"] = json_bytes({"tags": ["rubble"], "column": column, "mincount": 0, "maxcount": 1, "attempts": 1, "inbuilding": True, "biomes": {"if_any": ["#minecraft:is_nether"]}})
    ids = {b.id for b in buildings}
    rules = []
    used = set()
    for b in buildings:
        if not b.security:
            raise ValueError(f"{b.id}: no security class")
        if b.security not in STOCK_SECURITY_CLASSES and b.security not in NEW_SECURITY_CLASSES:
            raise ValueError(f"{b.id}: unknown security class {b.security}")
        used.add(b.security)
        # the full type string Core sees, with a priority that outranks the stock fallback rule
        rules.append({"type_prefix": f"{NAMESPACE}:{b.id}", "class": b.security, "priority": 10})
    files[f"data/{NAMESPACE}/building_security/furnished.json"] = json_bytes({
        "schema_version": 1,
        "classes": {name: {k: v for k, v in spec.items() if k != "panel"} for name, spec in NEW_SECURITY_CLASSES.items() if name in used},
        "rules": rules,
    })
    for module in (city_valewood, city_ironhaven, city_blackwater):
        zones = module.zones()
        if not zones:
            continue
        rings = []
        last = 0.0
        for within, picks in zones:
            if within <= last or within > 1.0:
                raise ValueError(f"{module.CITY}: zones must grow from 0 to 1")
            last = within
            for building_id, weight in picks:
                if building_id not in ids:
                    raise ValueError(f"{module.CITY}: zone names the unknown building {building_id}")
            rings.append({"within": within, "buildings": [{"id": f"{NAMESPACE}:{building_id}", "weight": weight} for building_id, weight in picks]})
        if last != 1.0:
            raise ValueError(f"{module.CITY}: the last zone must reach 1.0")
        files[f"data/{NAMESPACE}/city_character/{module.CITY}.json"] = json_bytes({"schema_version": 1, "city": module.CITY, "style": f"{NAMESPACE}:{module.CITY}", "keep_multi_buildings": bool(getattr(module, "KEEP_MULTI_BUILDINGS", False)), "zones": rings})
    return files


if __name__ == "__main__":
    for name in sorted(package()):
        print(name)
