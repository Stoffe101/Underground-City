package io.github.stoffe101.undergroundcity;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;

import java.util.List;
import java.util.Random;

/**
 * The shape of the archipelago world as pure arithmetic: which columns are land, how far a column lies from the nearest shore, where the
 * ground under a city is flattened, and how warm and wet each island is. Nothing here knows about Minecraft (so unit tests and the
 * silhouette preview can use it); {@link IslandField} turns it into terrain density functions.
 *
 * <p>The plan is data (generated by {@code scripts/plan_archipelago.py} from {@code content/region-blueprints/archipelago}); there is no
 * coordinate in this file. Land is the union of the "add" shapes (a disc per island, a capsule per cape) minus the "carve" shapes (a harbour
 * bay), and its edge is moved by a fixed-seed noise so the shores are not circles. The noise does not depend on the world seed: every new
 * world has the same three islands, the seed only changes the hills, trees and rivers on them.
 */
public record IslandPlan(Shore shore, double openSea, double straitSea, List<Shape> shapes, List<Plateau> plateaus, List<Climate> climate) {
    public record Shore(double amplitude, double scale, long seed) {
        static final Codec<Shore> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.DOUBLE.fieldOf("amplitude").forGetter(Shore::amplitude), Codec.DOUBLE.fieldOf("scale").forGetter(Shore::scale),
            Codec.LONG.fieldOf("seed").forGetter(Shore::seed)).apply(i, Shore::new));
    }

    /** A disc ({@code center}) or a capsule ({@code from} to {@code to}); a carved shape removes land (a bay). */
    public record Shape(String island, String op, String type, List<Double> center, List<Double> from, List<Double> to, double radius) {
        static final Codec<Shape> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.STRING.fieldOf("island").forGetter(Shape::island), Codec.STRING.fieldOf("op").forGetter(Shape::op),
            Codec.STRING.fieldOf("type").forGetter(Shape::type),
            Codec.DOUBLE.listOf().optionalFieldOf("center", List.of()).forGetter(Shape::center),
            Codec.DOUBLE.listOf().optionalFieldOf("from", List.of()).forGetter(Shape::from),
            Codec.DOUBLE.listOf().optionalFieldOf("to", List.of()).forGetter(Shape::to),
            Codec.DOUBLE.fieldOf("radius").forGetter(Shape::radius)).apply(i, Shape::new));

        boolean carve() { return op.equals("carve"); }

        /** Positive inside the shape, by that many blocks from its edge; negative outside. */
        double inside(double x, double z) {
            if (type.equals("disc")) return radius - Math.hypot(x - center.get(0), z - center.get(1));
            double ax = from.get(0), az = from.get(1), bx = to.get(0), bz = to.get(1);
            double dx = bx - ax, dz = bz - az, length2 = dx * dx + dz * dz;
            double t = length2 == 0 ? 0 : Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / length2));
            return radius - Math.hypot(x - (ax + dx * t), z - (az + dz * t));
        }
    }

    /** Ground held level under a city: full strength inside {@code radius}, easing away over {@code ease} blocks. */
    public record Plateau(String id, List<Double> center, double radius, double ease, int groundY) {
        static final Codec<Plateau> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.STRING.fieldOf("id").forGetter(Plateau::id), Codec.DOUBLE.listOf().fieldOf("center").forGetter(Plateau::center),
            Codec.DOUBLE.fieldOf("radius").forGetter(Plateau::radius), Codec.DOUBLE.fieldOf("ease").forGetter(Plateau::ease),
            Codec.INT.fieldOf("ground_y").forGetter(Plateau::groundY)).apply(i, Plateau::new));
    }

    /** How warm and wet an island is (the Minecraft climate parameters, roughly -1 to 1), felt out to {@code radius} from its centre. */
    public record Climate(String island, List<Double> center, double radius, double temperature, double humidity) {
        static final Codec<Climate> CODEC = RecordCodecBuilder.create(i -> i.group(
            Codec.STRING.fieldOf("island").forGetter(Climate::island), Codec.DOUBLE.listOf().fieldOf("center").forGetter(Climate::center),
            Codec.DOUBLE.fieldOf("radius").forGetter(Climate::radius), Codec.DOUBLE.fieldOf("temperature").forGetter(Climate::temperature),
            Codec.DOUBLE.fieldOf("humidity").forGetter(Climate::humidity)).apply(i, Climate::new));
    }

    public static final Codec<IslandPlan> CODEC = RecordCodecBuilder.create(i -> i.group(
        Shore.CODEC.fieldOf("shore").forGetter(IslandPlan::shore), Codec.DOUBLE.fieldOf("open_sea").forGetter(IslandPlan::openSea),
        Codec.DOUBLE.fieldOf("strait_sea").forGetter(IslandPlan::straitSea), Shape.CODEC.listOf().fieldOf("shapes").forGetter(IslandPlan::shapes),
        Plateau.CODEC.listOf().fieldOf("plateaus").forGetter(IslandPlan::plateaus), Climate.CODEC.listOf().fieldOf("climate").forGetter(IslandPlan::climate)
    ).apply(i, IslandPlan::new));

    // ------------------------------------------------------------------------------------------------------ the shore

    /** Blocks from the shore: positive on land (the distance to the water), negative at sea (minus the distance to the nearest land). */
    public double distanceToShore(double x, double z) {
        double land = -1.0e4, bay = -1.0e4;
        for (Shape shape : shapes) {
            double inside = shape.inside(x, z);
            if (shape.carve()) bay = Math.max(bay, inside); else land = Math.max(land, inside);
        }
        return Math.min(land, -bay) + shore.amplitude() * (0.65 * noise(x / shore.scale(), z / shore.scale()) + 0.35 * noise(2.3 * x / shore.scale() + 17.0, 2.3 * z / shore.scale() - 9.0));
    }

    /**
     * The continentalness the biome and terrain functions are given (about -1.2 deep ocean to 1 far inland). Land climbs from the coast
     * (-0.19) to a gentle interior; straits are a shallow ocean so a bridge's piers stay short; beyond them the sea deepens.
     */
    public double continents(double x, double z) {
        double d = distanceToShore(x, z);
        if (d >= 0) return curve(d, LAND_AT, LAND);
        return curve(-d, new double[] {0, 35, 70, 230, 520}, new double[] {-0.19, -0.33, straitSea, straitSea, openSea});
    }

    private static final double[] LAND_AT = {0, 30, 130, 260, 420}, LAND = {-0.19, -0.08, 0.12, 0.30, 0.38};

    /** Piecewise-linear curve through (position, value) pairs; outside the ends the end values hold. */
    static double curve(double at, double[] positions, double[] values) {
        if (at <= positions[0]) return values[0];
        for (int i = 1; i < positions.length; i++) {
            if (at <= positions[i]) {
                double t = (at - positions[i - 1]) / (positions[i] - positions[i - 1]);
                return values[i - 1] + (values[i] - values[i - 1]) * t;
            }
        }
        return values[values.length - 1];
    }

    // ------------------------------------------------------------------------------------------------------ plateaus and climate

    /** 1 on the flat ground under a city (and the arrival site), easing to 0. */
    public double plateau(double x, double z) { return plateau(x, z, 0, 1.0); }

    /**
     * The same, tighter: the plateau's radius reduced by {@code shrink} blocks and its easing multiplied by {@code easeScale}. The climate under a city is held at plains (so that no forest
     * grows over streets and roofs), but only over the built ground and a short margin: the countryside beyond keeps its island's own climate, which is what makes the three islands look different.
     */
    public double plateau(double x, double z, double shrink, double easeScale) {
        double best = 0;
        for (Plateau plateau : plateaus) {
            double distance = Math.hypot(x - plateau.center().get(0), z - plateau.center().get(1));
            double t = Math.max(0, Math.min(1, 1 - (distance - (plateau.radius() - shrink)) / (plateau.ease() * easeScale)));
            best = Math.max(best, t * t * (3 - 2 * t));
        }
        return best;
    }

    /** The weights of each island's climate at a point and the share of the plan they cover (0 on open sea). */
    public double climate(double x, double z, boolean temperature, double fallback) {
        double sum = 0, weighted = 0;
        for (Climate c : climate) {
            double distance = Math.hypot(x - c.center().get(0), z - c.center().get(1));
            double t = Math.max(0, Math.min(1, 1 - (distance - 0.7 * c.radius()) / (0.5 * c.radius())));
            double w = t * t * (3 - 2 * t);
            sum += w;
            weighted += w * (temperature ? c.temperature() : c.humidity());
        }
        if (sum <= 1.0e-6) return fallback;
        double share = Math.min(1, sum);
        return (weighted / sum) * share + fallback * (1 - share);
    }

    // ------------------------------------------------------------------------------------------------------ noise

    private static final java.util.concurrent.ConcurrentHashMap<Long, Noise> NOISES = new java.util.concurrent.ConcurrentHashMap<>();

    private double noise(double x, double z) {
        return NOISES.computeIfAbsent(shore.seed(), Noise::new).at(x, z);
    }

    /** Fixed-seed 2D gradient noise in about [-1, 1] (java.util.Random is specified, so it is the same on every JVM). */
    static final class Noise {
        private final int[] perm = new int[512];
        private final double[] gx = new double[256], gz = new double[256];

        Noise(long seed) {
            Random random = new Random(seed);
            int[] p = new int[256];
            for (int i = 0; i < 256; i++) p[i] = i;
            for (int i = 255; i > 0; i--) { int j = random.nextInt(i + 1); int t = p[i]; p[i] = p[j]; p[j] = t; }
            for (int i = 0; i < 512; i++) perm[i] = p[i & 255];
            for (int i = 0; i < 256; i++) { double a = random.nextDouble() * Math.PI * 2; gx[i] = Math.cos(a); gz[i] = Math.sin(a); }
        }

        double at(double x, double z) {
            int xi = (int) Math.floor(x), zi = (int) Math.floor(z);
            double xf = x - xi, zf = z - zi;
            double u = fade(xf), v = fade(zf);
            double n00 = dot(xi, zi, xf, zf), n10 = dot(xi + 1, zi, xf - 1, zf), n01 = dot(xi, zi + 1, xf, zf - 1), n11 = dot(xi + 1, zi + 1, xf - 1, zf - 1);
            double nx0 = n00 + u * (n10 - n00), nx1 = n01 + u * (n11 - n01);
            return Math.max(-1, Math.min(1, (nx0 + v * (nx1 - nx0)) * 1.4));
        }

        private double dot(int ix, int iz, double dx, double dz) {
            int h = perm[(perm[ix & 255] + iz) & 511] & 255;
            return gx[h] * dx + gz[h] * dz;
        }

        private static double fade(double t) { return t * t * t * (t * (t * 6 - 15) + 10); }
    }
}
