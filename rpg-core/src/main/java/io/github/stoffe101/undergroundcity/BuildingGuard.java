/**
 * City buildings belong to somebody (D-105). Inside the volume of a generated building (the chunk, from under its deepest cellar to over its roof; see {@link CityBuildings}) a visitor cannot
 * break, place, pour, push, blast or burn anything: the walls, the windows, the doors, the furniture and the containers are the property, and the one way in is the door, which a lockpicker
 * can open on {@link LockpickScreen} ({@link LockService}). Everywhere else in the world (the countryside, a street, a park, an open lot, a wayside shelter's surroundings) nothing changes: gathering
 * and building stay possible, and a registered home still answers to {@link ResidenceGuard}, which keeps authority inside it.
 *
 * <p>Honest limits (also in the documents): a building that is not generated by Lost Cities (a district placed by Core, a modded structure) is not covered; a roof reached from outside by a
 * stair of placed blocks is inside the volume but its stair door is locked like any other exterior door, and an open stairwell without a door is a way in this version does not close;
 * a mod that changes blocks without firing Forge's events (a gun that shatters glass by its own rule) is not covered until measured. Creative mode and operators are never stopped.
 */
public final class BuildingGuard {
    private static final Map<Player, Long> TOLD = new WeakHashMap<>();

    /** The building volume that protects this position for this actor, or empty. A registered home's own guard keeps authority over what it covers. */
    static Optional<CityBuildings.Building> protectedAt(ServerLevel level, BlockPos pos) {
        Optional<CityBuildings.Building> building = CityBuildings.INSTANCE.at(level, pos);
        if (building.isEmpty()) return building;
        CrewLedger ledger = CrewService.ledger(level.getServer());
        if (ledger != null && ledger.residenceAt(level.dimension().location().toString(), pos) != null) return Optional.empty();
        return building;
    }

    private static boolean bypass(ServerPlayer player) { return player.isCreative(); }

    private static void tell(ServerPlayer player, String text) {
        long now = player.level().getGameTime();
        Long last = TOLD.get(player);
        if (last != null && now - last < 20) return;
        TOLD.put(player, now);
        player.displayClientMessage(Component.literal(text), true);
    }

    static final String REFUSAL = "This building belongs to someone. Its walls, windows and furniture are not yours to break; the door is the way in.";

    // ------------------------------------------------------------------------------------------------ building

    @SubscribeEvent
    public void breakBlock(BlockEvent.BreakEvent event) {
        if (!(event.getPlayer() instanceof ServerPlayer player) || !(event.getLevel() instanceof ServerLevel level) || bypass(player)) return;
        if (protectedAt(level, event.getPos()).isPresent()) {
            event.setCanceled(true);
            tell(player, REFUSAL);
        }
    }

    @SubscribeEvent
    public void placeBlock(BlockEvent.EntityPlaceEvent event) {
        if (!(event.getEntity() instanceof ServerPlayer player) || !(event.getLevel() instanceof ServerLevel level) || bypass(player)) return;
        if (protectedAt(level, event.getPos()).isPresent()) {
            event.setCanceled(true);
            tell(player, "You cannot build inside someone else's building.");
        } else if (event.getPlacedBlock().isSignalSource() && nearLockedDoor(level, event.getPos())) {
            // the street in front of a door is not part of the building, but a button, a plate or a block of redstone put against the door opens it as surely as a hand
            event.setCanceled(true);
            tell(player, "You cannot rig a signal next to somebody else's locked door.");
        }
    }

    /** How near to a locked door a visitor may not put anything that gives a redstone signal. */
    static final int SIGNAL_REACH = 2;

    /** True when a locked exterior door of a building stands within {@link #SIGNAL_REACH} blocks of the position. */
    static boolean nearLockedDoor(ServerLevel level, BlockPos pos) {
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
        for (int dx = -SIGNAL_REACH; dx <= SIGNAL_REACH; dx++) for (int dz = -SIGNAL_REACH; dz <= SIGNAL_REACH; dz++) for (int dy = -2; dy <= 1; dy++) {
            p.set(pos.getX() + dx, pos.getY() + dy, pos.getZ() + dz);
            if (!level.isLoaded(p)) continue;
            BlockState state = level.getBlockState(p);
            if (!(state.getBlock() instanceof DoorBlock) || state.getValue(DoorBlock.HALF) != DoubleBlockHalf.LOWER) continue;
            Optional<CityBuildings.Building> found = protectedAt(level, p);
            if (found.isPresent() && found.get().locked() && exterior(level, p.immutable(), state)) return true;
        }
        return false;
    }

    /** A bucket empties or fills only outside a building's volume. */
    @SubscribeEvent
    public void bucket(FillBucketEvent event) {
        if (!(event.getEntity() instanceof ServerPlayer player) || !(event.getLevel() instanceof ServerLevel level) || bypass(player)) return;
        if (!(event.getTarget() instanceof net.minecraft.world.phys.BlockHitResult hit)) return;
        for (BlockPos pos : List.of(hit.getBlockPos(), hit.getBlockPos().relative(hit.getDirection()))) {
            if (protectedAt(level, pos).isPresent()) { event.setCanceled(true); tell(player, "You cannot pour or scoop anything inside someone else's building."); return; }
        }
    }

    // ------------------------------------------------------------------------------------------------ the door

    /** How far above a block to look for a roof: a Lost Cities building is at most eight floors of six blocks and a parapet, so a roof is always within this reach of its own ground floor. */
    static final int ROOF_REACH = 64;
    /** The reach in force; a test world is crowded (other tests build above a house), so its tests narrow it to the height of the house they built. */
    static volatile int roofReach = ROOF_REACH;

    /**
     * Whether nothing solid stands in the column above this block within {@link #ROOF_REACH} (leaves do not count: a tree is not a roof). It reads the blocks, and not {@code canSeeSky} (which asks the
     * light engine and is wrong for a few ticks after a change) or the height map (which sees a test world's ceiling, a test found, a hundred blocks up). The reach is what keeps a lobby under a
     * tall roof "inside" and a street under the open sky "outside".
     */
    static boolean exposed(ServerLevel level, BlockPos pos) {
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
        int top = Math.min(level.getMaxBuildHeight() - 1, pos.getY() + roofReach);
        for (int y = pos.getY(); y <= top; y++) {
            BlockState state = level.getBlockState(p.set(pos.getX(), y, pos.getZ()));
            if (state.blocksMotion() && !state.is(net.minecraft.tags.BlockTags.LEAVES)) return false;
        }
        return true;
    }

    /** True when the door's front or back side leads outside (the street, a roof): the side a visitor stands on. A door with both sides under a roof, well in, is an inside door. */
    static boolean exterior(ServerLevel level, BlockPos lower, BlockState state) {
        Direction facing = state.getValue(DoorBlock.FACING);
        return leadsOut(level, lower, facing) || leadsOut(level, lower, facing.getOpposite());
    }

    /** How far beyond a door a covered step may reach before the open sky: the eaves or a porch roof over a front door (D-150). */
    static final int COVERED_STEP = 3;

    /**
     * Whether one side of a door leads outside: the cell before it is open to the sky (the rule before D-150, kept so that no door that was locked becomes an inside door), or open floor leads
     * from the door, within {@link #COVERED_STEP} blocks, to a cell that is. A Valewood house's front door has its step under the eaves and a roofed hall behind it, so neither cell beside it
     * was open to the sky and the door was taken for an inside door, never locked (found by the Thief scenario, run 3). A wall, a closed door or furniture in the way ends the search.
     */
    static boolean leadsOut(ServerLevel level, BlockPos lower, Direction side) {
        if (exposed(level, lower.relative(side).above())) return true;
        for (int k = 1; k < COVERED_STEP; k++) {
            BlockPos cell = lower.relative(side, k);
            if (level.getBlockState(cell).blocksMotion() || level.getBlockState(cell.above()).blocksMotion()) return false;
            if (exposed(level, lower.relative(side, k + 1).above())) return true;
        }
        return false;
    }

    /**
     * A closed door's leaf is 3/16 of a block thick and fills the edge of its block that lies opposite the door's facing; the plane that divides "in front of the door" from "behind it" is the middle of
     * that slab, this far from the block's centre toward that edge. The first human playtest found that this used to be the block's <i>centre</i>: a player who walks into a door and stops against
     * its leaf stands 0.3 from the leaf's face, which is 0.0125 past the centre, so holding W made the street side look like the room side and the door opened by hand.
     */
    static final double LEAF_PLANE = 0.5 - 1.5 / 16.0;

    /** True when the point is on the side the door faces (its front), measured against the leaf and not against the middle of the block. */
    static boolean inFront(BlockPos lower, BlockState state, Vec3 at) {
        Direction facing = state.getValue(DoorBlock.FACING);
        Vec3 centre = Vec3.atCenterOf(lower);
        double along = (at.x - centre.x) * facing.getStepX() + (at.z - centre.z) * facing.getStepZ();
        return along > -LEAF_PLANE;
    }

    /** True when the player stands on the sky side of the door (a visitor); a person on the inside can always leave. */
    static boolean outsideSide(ServerLevel level, BlockPos lower, BlockState state, Vec3 at) {
        Direction facing = state.getValue(DoorBlock.FACING);
        boolean frontSky = leadsOut(level, lower, facing), backSky = leadsOut(level, lower, facing.getOpposite());
        if (frontSky && backSky) return true;
        return inFront(lower, state, at) ? frontSky : backSky;
    }

    /** How long a locked door that somebody inside opened to leave stands open before it is shut again (five seconds of active time): long enough to walk out, too short to be a way in. */
    static final long EXIT_TICKS = 100;

    /** The lower half of a door block, whichever half was clicked. */
    static BlockPos lowerOf(BlockPos pos, BlockState state) { return state.getValue(DoorBlock.HALF) == DoubleBlockHalf.UPPER ? pos.below() : pos; }

    @SubscribeEvent(priority = EventPriority.HIGH)
    public void use(PlayerInteractEvent.RightClickBlock event) {
        if (!(event.getEntity() instanceof ServerPlayer player) || !(event.getLevel() instanceof ServerLevel level) || bypass(player)) return;
        BlockState state = level.getBlockState(event.getPos());
        if (!(state.getBlock() instanceof DoorBlock)) return;
        BlockPos lower = lowerOf(event.getPos(), state);
        // a building with units to let registers them when somebody comes to its door (D-127): a vacant house's door is then its showroom door, a let one its tenant's
        CityBuildings.INSTANCE.at(level, lower).ifPresent(b -> CityHomes.ensureBuilding(level, b));
        Optional<CityBuildings.Building> found = protectedAt(level, lower);
        if (found.isEmpty() || !found.get().locked()) return;
        BlockState lowerState = lower.equals(event.getPos()) ? state : level.getBlockState(lower);
        // a staff door of an open building (D-159): shut to the public side and locked like its street door, so a lockpick opens it; from behind it opens by hand
        if (lowerState.getBlock() instanceof DoorBlock && !CityHomes.holdsKey(player, found.get()) && StaffZones.staffDoorNow(level, found.get(), lower)
                && StaffZones.onPublicSide(level, found.get(), lower, player.position())) {
            long now = LockService.clock(level.getServer());
            if (PropertyLocks.get(level.getServer()).breached(lower, now) || lowerState.getValue(DoorBlock.OPEN)) { byHand(event, player, level, lower, lowerState); return; }
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.SUCCESS);
            if (event.getHand() != InteractionHand.MAIN_HAND) return;
            if (!LockService.isPick(player.getMainHandItem())) { tell(player, "Staff only. The door is locked."); return; }
            var security = found.get().security();
            String refusal = LockService.begin(player, level, new LockService.Target(LockService.Kind.DOOR, lower, security.lockProfile(), found.get().city(), security.id(), "Staff door", 1));
            if (refusal != null) tell(player, refusal);
            return;
        }
        // an open shop's street door is a shop door (D-146), and a fence's door at the fence's hours lets in whoever brings stolen goods (D-147); crouching with an empty hand still cases it
        if (openToPublic(level, found.get(), player) && !(Casing.wants(player) && lowerState.getBlock() instanceof DoorBlock && outsideSide(level, lower, lowerState, player.position()))) {
            PropertyLocks.get(level.getServer()).exitOpen(lower, LockService.clock(level.getServer()) + EXIT_TICKS);
            byHand(event, player, level, lower, lowerState);
            return;
        }
        if (!(lowerState.getBlock() instanceof DoorBlock) || !exterior(level, lower, lowerState)) return;
        // a Technician's tool at a street door that stands in for the building's utility panel (D-158) is work on its systems, not an attempt on its lock
        if (event.getHand() == InteractionHand.MAIN_HAND && outsideSide(level, lower, lowerState, player.position()) && TechWork.useDoor(player, level, found.get())) {
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.SUCCESS);
            return;
        }
        // casing (D-144): crouched with an empty hand at a street door, from the street, a thief reads the place instead of trying it
        if (Casing.wants(player) && outsideSide(level, lower, lowerState, player.position()) && !CityHomes.holdsKey(player, found.get())) {
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.SUCCESS);
            if (event.getHand() == InteractionHand.MAIN_HAND) Casing.caseDoor(player, level, found.get(), lower);
            return;
        }
        long now = LockService.clock(level.getServer());
        boolean keypad = SecurityCraftTrial.isKeypadDoor(lowerState);
        // a keypad door that stands open shuts on a click, as any door does; SecurityCraft would ask for its code again (security run 10: a held click opened it, then asked)
        if (keypad && lowerState.getValue(DoorBlock.OPEN)) {
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.SUCCESS);
            if (event.getHand() == InteractionHand.MAIN_HAND) ((DoorBlock) lowerState.getBlock()).setOpen(player, level, lowerState, lower, false);
            return;
        }
        // a keypad door (the SecurityCraft trial, D-140) would ask for its code on the way out too, even while it stands unlocked after somebody came in: Core opens it for the person leaving
        if (keypad && (!outsideSide(level, lower, lowerState, player.position()) || CityHomes.holdsKey(player, found.get()))) {
            PropertyLocks.get(level.getServer()).exitOpen(lower, now + EXIT_TICKS);
            event.setCanceled(true);
            event.setCancellationResult(InteractionResult.SUCCESS);
            if (event.getHand() == InteractionHand.MAIN_HAND) {
                ((DoorBlock) lowerState.getBlock()).setOpen(player, level, lowerState, lower, true);
            }
            return;
        }
        if (PropertyLocks.get(level.getServer()).breached(lower, now)) { byHand(event, player, level, lower, lowerState); return; }   // somebody picked it a moment ago
        if (lowerState.getValue(DoorBlock.OPEN)) { byHand(event, player, level, lower, lowerState); return; }   // a click on a door that stands open only shuts it
        if (!outsideSide(level, lower, lowerState, player.position()) || CityHomes.holdsKey(player, found.get())) {
            // from the inside a door always opens, and a tenant of a flat in the building has a key to its street door (D-127); either way it shuts itself again a few seconds later
            PropertyLocks.get(level.getServer()).exitOpen(lower, now + EXIT_TICKS);
            byHand(event, player, level, lower, lowerState);
            return;
        }
        // from the street a trial keypad door asks for its code itself; Core judges the entry when it opens. A lockpick still works on it, through Core's lock.
        if (keypad && !LockService.isPick(player.getMainHandItem())) return;
        // locked: the click does not open it; with a lockpick it starts the lock instead
        event.setCanceled(true);
        event.setCancellationResult(InteractionResult.SUCCESS);
        if (event.getHand() != InteractionHand.MAIN_HAND) return;
        CityBuildings.Building building = found.get();
        var security = building.security();
        String profile = security.lockProfile();
        String label = security.label().isEmpty() ? "Door" : Character.toUpperCase(security.label().charAt(0)) + security.label().substring(1);
        String refusal = LockService.begin(player, level, new LockService.Target(LockService.Kind.DOOR, lower, profile, building.city(), security.id(), label, 1));
        if (refusal != null) tell(player, refusal);
    }

    /**
     * Whether a building's street door is open to the public now: a shop while its shopkeeper is in (D-146), a fence's building while the fence is in (D-147), the latter only to a person carrying
     * stolen goods when {@code player} is given (with no player, whether the door may stand open at all). Nobody searches the furniture of a building that is open ({@link BurglarySearch}).
     */
    static boolean openToPublic(ServerLevel level, CityBuildings.Building building, ServerPlayer player) {
        if (ShopCounters.openNow(level, building)) return true;
        return FenceService.receivingNow(level, building) && (player == null || FenceService.carriesStolen(player));
    }

    /**
     * An iron door does not open by hand. Where the guard lets a person through one (from the inside, with a key, a shop in its hours, a fence's at theirs, a lock picked a moment ago), Core
     * opens or shuts it as a click would a wooden door (D-151): the Ironhaven flats' street doors are iron, and a tenant could not get in, nor a thief out of the club.
     */
    static void byHand(PlayerInteractEvent.RightClickBlock event, ServerPlayer player, ServerLevel level, BlockPos lower, BlockState lowerState) {
        if (!(lowerState.getBlock() instanceof DoorBlock door) || door.type().canOpenByHand()) return;
        event.setCanceled(true);
        event.setCancellationResult(InteractionResult.SUCCESS);
        if (event.getHand() == InteractionHand.MAIN_HAND) door.setOpen(player, level, lowerState, lower, !lowerState.getValue(DoorBlock.OPEN));
    }

    // ------------------------------------------------------------------------------------------------ the door itself

    /**
     * The click is one way a door opens; it is not the only one. A door answers to redstone, to a mod that calls {@code setOpen}, to a command, and a client that predicts the click shows it open for a
     * moment whatever the server decides. The lock is therefore also a rule about the door's <i>state</i>: a locked exterior door of a building stands closed unless somebody picked it, or somebody
     * inside opened it to leave a moment ago ({@link PropertyLocks#openOnPurpose}), or a builder in creative mode is standing by. Anything else found open is shut, within a tick of a block update
     * next to it and within half a second for any door close to a player.
     */
    private static final java.util.Set<Long> RECHECK = new java.util.LinkedHashSet<>();
    /** Doors this watch has shut (a test and the burglary report read it). */
    static volatile int shutByWatch;

    /** Shuts the door at this lower half when it stands open without a reason. Returns whether it did. */
    static boolean enforce(ServerLevel level, BlockPos lower) {
        BlockState state = level.getBlockState(lower);
        if (!(state.getBlock() instanceof DoorBlock door) || state.getValue(DoorBlock.HALF) != DoubleBlockHalf.LOWER || !state.getValue(DoorBlock.OPEN)) return false;
        Optional<CityBuildings.Building> found = protectedAt(level, lower);
        if (found.isEmpty() || !found.get().locked() || !exterior(level, lower, state)) return false;
        if (PropertyLocks.get(level.getServer()).openOnPurpose(lower)) return false;
        if (openToPublic(level, found.get(), null)) return false;   // a shop's door may stand open in business hours, a fence's in theirs
        for (Player near : level.getEntitiesOfClass(Player.class, new net.minecraft.world.phys.AABB(lower).inflate(8.0))) if (near.isCreative()) return false;
        door.setOpen(null, level, state, lower, false);
        shutByWatch++;
        return true;
    }

    /** A block next to a door changed: look at the door once the update has run. */
    @SubscribeEvent
    public void neighbourChanged(BlockEvent.NeighborNotifyEvent event) {
        if (!(event.getLevel() instanceof ServerLevel level) || level.dimension() != net.minecraft.world.level.Level.OVERWORLD) return;
        BlockPos pos = event.getPos();
        for (Direction side : event.getNotifiedSides()) {
            BlockPos near = pos.relative(side);
            if (level.isLoaded(near) && level.getBlockState(near).getBlock() instanceof DoorBlock) synchronized (RECHECK) { if (RECHECK.size() < 256) RECHECK.add(near.asLong()); }
        }
    }

    private static int watchClock;

    @SubscribeEvent
    public void watchTick(net.minecraftforge.event.TickEvent.ServerTickEvent event) {
        if (event.phase != net.minecraftforge.event.TickEvent.Phase.END) return;
        ServerLevel level = event.getServer().overworld();
        if (level == null) return;
        long[] due;
        synchronized (RECHECK) {
            if (RECHECK.isEmpty()) due = new long[0];
            else { due = RECHECK.stream().mapToLong(Long::longValue).toArray(); RECHECK.clear(); }
        }
        for (long key : due) {
            BlockPos pos = BlockPos.of(key);
            if (!level.isLoaded(pos)) continue;
            BlockState state = level.getBlockState(pos);
            if (state.getBlock() instanceof DoorBlock) enforce(level, lowerOf(pos, state));
        }
        if (++watchClock < 10) return;
        watchClock = 0;
        for (ServerPlayer player : level.players()) watchAround(level, player.blockPosition());
    }

    /** Shuts every door standing open without a reason within six blocks of a position (and three above, two below); returns how many it shut. */
    static int watchAround(ServerLevel level, BlockPos at) {
        // the watch comes round every ten ticks: a plan Lost Cities cannot give without waiting on its generation workers is asked next time (D-167)
        for (BlockPos p : new BlockPos[] {at, at.offset(6, 0, 6), at.offset(-6, 0, -6)}) if (!CityBuildings.INSTANCE.askable(level, p.getX() >> 4, p.getZ() >> 4)) return 0;
        if (CityBuildings.INSTANCE.at(level, at).isEmpty() && CityBuildings.INSTANCE.at(level, at.offset(6, 0, 6)).isEmpty() && CityBuildings.INSTANCE.at(level, at.offset(-6, 0, -6)).isEmpty()) return 0;
        int shut = 0;
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
        for (int dx = -6; dx <= 6; dx++) for (int dz = -6; dz <= 6; dz++) for (int dy = -2; dy <= 3; dy++) {
            p.set(at.getX() + dx, at.getY() + dy, at.getZ() + dz);
            if (!level.isLoaded(p)) continue;
            BlockState state = level.getBlockState(p);
            if (state.getBlock() instanceof DoorBlock && state.getValue(DoorBlock.OPEN) && state.getValue(DoorBlock.HALF) == DoubleBlockHalf.LOWER && enforce(level, p.immutable())) shut++;
        }
        return shut;
    }

    // ------------------------------------------------------------------------------------------------ everything else that changes blocks

    /** A piston may not move or break anything of a building from outside nor push anything across its boundary. */
    @SubscribeEvent
    public void piston(PistonEvent.Pre event) {
        if (!(event.getLevel() instanceof ServerLevel level)) return;
        List<BlockPos> touched = new ArrayList<>();
        touched.add(event.getPos());
        touched.add(event.getFaceOffsetPos());
        PistonStructureResolver structure = event.getStructureHelper();
        if (structure != null && structure.resolve()) {
            Direction push = event.getPistonMoveType().isExtend ? event.getDirection() : event.getDirection().getOpposite();
            for (BlockPos moved : structure.getToPush()) { touched.add(moved); touched.add(moved.relative(push)); }
            touched.addAll(structure.getToDestroy());
        }
        for (BlockPos pos : touched) if (protectedAt(level, pos).isPresent()) { event.setCanceled(true); return; }
    }

    /** A blast leaves a building's blocks standing. */
    @SubscribeEvent
    public void explode(ExplosionEvent.Detonate event) {
        if (!(event.getLevel() instanceof ServerLevel level)) return;
        event.getAffectedBlocks().removeIf(pos -> protectedAt(level, pos).isPresent());
    }

    @SubscribeEvent
    public void mobGriefing(EntityMobGriefingEvent event) {
        if (event.getEntity() != null && event.getEntity().level() instanceof ServerLevel level && protectedAt(level, event.getEntity().blockPosition()).isPresent()) event.setResult(Event.Result.DENY);
    }

    @SubscribeEvent
    public void livingDestroys(LivingDestroyBlockEvent event) {
        if (event.getEntity().level() instanceof ServerLevel level && protectedAt(level, event.getPos()).isPresent()) event.setCanceled(true);
    }

    /** Test seam: the actor-independent question "would this position be protected". */
    static boolean covers(ServerLevel level, BlockPos pos) { return protectedAt(level, pos).isPresent(); }
}
