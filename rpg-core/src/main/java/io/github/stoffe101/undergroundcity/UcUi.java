    public static final int LEGAL = 0xff4fd1b8, UNDERGROUND = 0xffe2574c, UNDERGROUND_TEXT = 0xffff8f7e, AMBER = 0xffe8b04a, OK = 0xff7bd88f, WARN = 0xfff08a3c;
    public static final int IRONHAVEN = 0xffe07b39, VALEWOOD = 0xff86c45a, BLACKWATER = 0xff46a9e0;
