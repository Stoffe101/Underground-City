    public static Icon careerIcon(String career) {
        return switch (career == null ? "" : career.toLowerCase(Locale.ROOT)) {
            case "farmer" -> Icon.FARMER; case "smith" -> Icon.SMITH; case "gunsmith" -> Icon.GUNSMITH; case "technician" -> Icon.TECHNICIAN;
            default -> Icon.CITY;
        };
    }

    public static int careerColor(String career) {
        return switch (career == null ? "" : career.toLowerCase(Locale.ROOT)) {
            case "farmer" -> 0xff86c45a; case "smith" -> 0xffe07b39; case "gunsmith" -> 0xffd9b455; case "technician" -> 0xff46c9e0;
            default -> DIM;
        };
    }

    public static int cityColor(String city) {
        return switch (city == null ? "" : city.toLowerCase(Locale.ROOT)) {
            case "ironhaven" -> IRONHAVEN; case "valewood" -> VALEWOOD; case "blackwater" -> BLACKWATER; default -> DIM;
        };
    }

    // ---- 9-slice chrome
    private static void nine(GuiGraphics g, ResourceLocation texture, int texW, int texH, int u, int v, int sw, int sh, int corner, int x, int y, int w, int h) {
        int c = Math.min(corner, Math.min(w, h) / 2);
        if (c <= 0 || w <= 0 || h <= 0) return;
        g.blit(texture, x, y, c, c, u, v, c, c, texW, texH);
        g.blit(texture, x + w - c, y, c, c, u + sw - c, v, c, c, texW, texH);
        g.blit(texture, x, y + h - c, c, c, u, v + sh - c, c, c, texW, texH);
        g.blit(texture, x + w - c, y + h - c, c, c, u + sw - c, v + sh - c, c, c, texW, texH);
        if (w > 2 * c) {
            g.blit(texture, x + c, y, w - 2 * c, c, u + c, v, sw - 2 * c, c, texW, texH);
            g.blit(texture, x + c, y + h - c, w - 2 * c, c, u + c, v + sh - c, sw - 2 * c, c, texW, texH);
        }
        if (h > 2 * c) {
            g.blit(texture, x, y + c, c, h - 2 * c, u, v + c, c, sh - 2 * c, texW, texH);
            g.blit(texture, x + w - c, y + c, c, h - 2 * c, u + sw - c, v + c, c, sh - 2 * c, texW, texH);
        }
        if (w > 2 * c && h > 2 * c) g.blit(texture, x + c, y + c, w - 2 * c, h - 2 * c, u + c, v + c, sw - 2 * c, sh - 2 * c, texW, texH);
    }

    /** The enamel plate with brass rivets. */
