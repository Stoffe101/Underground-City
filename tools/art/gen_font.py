ORDER = list("ABCDEFGHIJKLMNOP" "QRSTUVWXYZ012345" "6789.,:;-+=/%|!?" "()[]<>#&'*_x")
COLS = 16


def build():
    rows = (len(ORDER) + COLS - 1) // COLS
    sheet = Image.new('RGBA', (COLS * 8, rows * 8), (0, 0, 0, 0))
    for i, ch in enumerate(ORDER):
        cx, cy = (i % COLS) * 8, (i // COLS) * 8
        for y, row in enumerate(G[ch]):
            for x, c in enumerate(row):
                if c == '#':
                    sheet.putpixel((cx + x, cy + y), (255, 255, 255, 255))
    out_dir = os.path.join(ASSETS, 'font')
    tex_dir = os.path.join(ASSETS, 'textures', 'font')     # bitmap providers read their image from textures/
    os.makedirs(out_dir, exist_ok=True)
    os.makedirs(tex_dir, exist_ok=True)
    sheet.save(os.path.join(tex_dir, 'uc_display.png'))
    chars = [''.join(ORDER[r * COLS:(r + 1) * COLS]).ljust(COLS, '\u0000') for r in range(rows)]
    provider = {'providers': [
        {'type': 'bitmap', 'file': 'underground_city:font/uc_display.png', 'ascent': 7, 'height': 8, 'chars': chars},
        {'type': 'space', 'advances': {' ': 4}}]}
    with open(os.path.join(out_dir, 'uc_display.json'), 'w') as fh:
        json.dump(provider, fh, indent=1)
    return sheet


if __name__ == '__main__':
    build()
    print('font written')
