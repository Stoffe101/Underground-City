ORDER = list(ICONS.keys())


def build():
    os.makedirs(ASSETS, exist_ok=True)
    sheet = Image.new('RGBA', (16 * 8, 16 * ((len(ORDER) + 7) // 8)), (0, 0, 0, 0))
    for i, name in enumerate(ORDER):
        ox, oy = (i % 8) * 16, (i // 8) * 16
        for y, row in enumerate(ICONS[name]):
            for x, ch in enumerate(row):
                if ch != '.':
                    sheet.putpixel((ox + x, oy + y), COL[ch])
    sheet.save(os.path.join(ASSETS, 'icons.png'))
    return sheet


if __name__ == '__main__':
    sheet = build()
    print(','.join(ORDER))
    prev = Image.new('RGBA', (sheet.width + 8, sheet.height + 8), (22, 33, 46, 255))
    prev.alpha_composite(sheet, (4, 4))
    # tinted copies
    tint = Image.new('RGBA', sheet.size, (0, 0, 0, 0))
    for (r, g, b) in ((0x4f, 0xd1, 0xb8),):
        for y in range(sheet.height):
            for x in range(sheet.width):
                p = sheet.getpixel((x, y))
                if p[3]:
                    tint.putpixel((x, y), (p[0] * r // 255, p[1] * g // 255, p[2] * b // 255, 255))
    prev2 = Image.new('RGBA', (sheet.width + 8, (sheet.height + 8) * 2), (22, 33, 46, 255))
    prev2.alpha_composite(prev, (0, 0))
    prev2.alpha_composite(tint, (4, sheet.height + 12))
    prev2.resize((prev2.width * 6, prev2.height * 6), Image.NEAREST).save(os.path.join(preview_dir(), 'icons1.png'))
